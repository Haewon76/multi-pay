package com.mallowlink.common.utils;

public class MaskUtil {

    public static String mask(String str) {
        return "*".repeat(str.length());
    }

    public static String maskSensitiveData(String message) {
        return message.replaceAll("((\"|\\\\\")endUserFirstName(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")endUserLastName(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")fullName(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")lastName(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")firstName(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")first_name(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")middle_name(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")last_name(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")birth_date(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")dateOfBirth(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")address(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")remitterName(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")beneficiaryName(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")city(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")email(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")receiverName(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")bankAccount(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")number(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")account_number(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5")
                .replaceAll("((\"|\\\\\")phoneNumber(\"|\\\\\")\\s*:\\s*(\"|\\\\\"))[^\"]+(\"|\\\\\")", "$1***$5");
    }
}
